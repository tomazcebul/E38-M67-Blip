"""INPA screens of the variant: screen/menu names, labels and the SGBD results each screen shows.

INPA object files (.IPO) keep their string constants in clear text, so the screen structure can be recovered without
the source (.IPS). Sources: Shared/BMW-StandardTools/EC-APPS/INPA/SGDAT (diagnosis: DDE41R.IPO = master, DDE41L.IPO =
slave; programming: 10DDE41A/B.ipo).

Writes out/inpa_screens.md. Every SGBD result referenced by a screen is checked against the SGBD jobs/results.
"""
import os
import re

import sgbd
import variant as V

SGDAT = os.path.join(V.SHARED, "BMW-StandardTools", "EC-APPS", "INPA", "SGDAT")
FILES = {"A": ("DDE41R.IPO", "10DDE41A.ipo"), "B": ("DDE41L.IPO", "10DDE41B.ipo")}
SKIP = {"TEST-Infotext", "ergebnisTextAusgabe", "ergebnisDigitalAusgabe", "ergebnisAnalogAusgabe",
        "ergebnisUmrechnungAnalogAusgabe", "ansteuerung", "inpainit", "inpaexit", "__inpa_startup__"}


def strings(path):
    d = open(path, "rb").read()
    return [m.group().decode("latin-1").strip() for m in re.finditer(rb"[ -~\xc0-\xff]{4,}", d)]


def screens(path):
    out, cur = [], None
    for s in strings(path):
        if s in SKIP:
            continue
        if re.fullmatch(r"[sm]_\w+", s):
            cur = [s, []]
            out.append(cur)
        elif cur is not None:
            cur[1].append(s)
    return out


def sgbd_names(path):
    """All job and result names documented in an SGBD (full documentation block at file offset 0x90)."""
    import struct
    raw, d = sgbd.read(path)
    o = struct.unpack_from("<I", raw, 0x90)[0]
    n = struct.unpack_from("<I", raw, o)[0]
    text = d[o + 4:o + 4 + n].decode("latin-1")
    return set(sgbd.jobs(raw, d)) | set(re.findall(r"(?:JOBNAME|RESULT):(\w+)", text))


def main():
    known = sgbd_names(V.SGBD_PRG)
    md = [f"# {V.NAME} ({V.V['role']}) – INPA screens", "",
          f"Generated by `tools/inpa.py` from the compiled INPA scripts in `BMW-StandardTools/EC-APPS/INPA/SGDAT` (no "
          f"`.IPS` sources available). Each row lists, in file order, the labels and the SGBD jobs/results the screen "
          f"uses; names not found in `{V.V['sgbd']}.prg` are marked *(not in SGBD)*.", ""]
    for f in FILES[V.KEY]:
        p = os.path.join(SGDAT, f)
        if not os.path.exists(p):
            md += [f"`{f}` not found.", ""]
            continue
        md += [f"## {f}", "", "| Screen / menu | Labels, jobs and results |", "|---|---|"]
        for name, items in screens(p):
            cells = []
            for it in items:
                if re.fullmatch(r"[A-Z0-9_]+(;[A-Z0-9_]+)*", it):
                    cells.append(", ".join(f"`{x}`" + ("" if x in known or not x.startswith(("STAT", "STEUERN"))
                                                       else " *(not in SGBD)*") for x in it.split(";")))
                else:
                    cells.append(it.replace("|", "/"))
            md.append(f"| `{name}` | {'; '.join(cells)} |")
        md.append("")
    with open(os.path.join(V.OUT, "inpa_screens.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(md))
    print(f"inpa_screens.md written ({', '.join(FILES[V.KEY])})")


if __name__ == "__main__":
    main()
