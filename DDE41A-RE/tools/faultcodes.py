"""Fault reports -> SGBD fault codes (Fehlerorte).

The fault memory read (KWP2000 service 0x18, handler at 0x0AB5C4 in the master) answers each stored fault with
the 16-bit word the fault entry's descriptor pointer points to (fault memory 0xC529, 28-byte entries, pointer table
in RAM 0xCAA2). Those descriptors are calibration labels of the form

    <fault code, 16 bit LE> <0|1> 0x41 <n> 0x28 ...

and every fault code of the SGBD (FORTTEXTE) has exactly one of them. In the label pointer table each descriptor
label is followed by the labels of the debounce configurations (R1 of fault_report) that belong to it. So every
fault report (R3 = (path << 4) | (error << 1)) is assigned to the nearest preceding descriptor label by label index.
This assignment is unambiguous for every fault index R3 >> 1 (checked below) and agrees with the CAN supervision
identified independently (CANP -> 0x0600/0x0601 "CAN-Bus privat", EGS1/ASC1 -> 0x1E00 "CAN-Bus").

Inputs: the combined image, out/labels.csv, out/fault_paths.csv (params.py), SGBD FORTTEXTE (+ English SGBD).
Outputs: out/fault_codes.csv (one row per fault report) and out/fault_codes.md (one row per fault code).
"""
import bisect
import collections
import csv
import os
import struct

import sgbd
import variant as V

EN_SGBD = os.path.join(V.SHARED, "BMW-StandardTools", "EDIABAS", "EnglishEcu", V.V["sgbd"] + ".prg")


def fault_texts():
    """{code: (German, English, [environment ids])} from FORTTEXTE (and FORTTEXTE_SL for the master's slave list)."""
    out = {}
    raw, d = sgbd.read(V.SGBD_PRG)
    t = sgbd.tables(raw, d)
    en = {}
    if os.path.exists(EN_SGBD):
        raw_en, d_en = sgbd.read(EN_SGBD)
        te = sgbd.tables(raw_en, d_en)
        en = {r[0].lower(): r[1].strip() for r in te.get("FORTTEXTE", [])[1:]}
    for r in t["FORTTEXTE"][1:]:
        if r[0].lower().startswith("0x"):
            e = en.get(r[0].lower(), "")
            out[int(r[0], 16)] = (r[1].strip(), "" if e == r[1].strip() else e, [x for x in r[2:] if x not in ("0x00", "")])
    env = {r[0].lower(): r[1].strip() for r in t.get("FUMWELTTEXTE", [[]])[1:]}
    return out, env


def descriptors(img, codes):
    """{label index: (address, code, raw bytes)} for the fault-code descriptor labels."""
    out = {}
    for r in csv.DictReader(open(os.path.join(V.OUT, "labels.csv"), encoding="utf-8")):
        a = int(r["label_address"], 16)
        o = a - V.BASE
        if not 0 <= o < len(img) - 8:
            continue
        w = struct.unpack_from("<H", img, o)[0]
        if w and w in codes and img[o + 3] == 0x41 and img[o + 5] == 0x28:
            out[int(r["index"])] = (a, w, img[o:o + 8])
    return out


def main():
    img = open(V.IMAGE, "rb").read()
    texts, env = fault_texts()
    desc = descriptors(img, texts)
    dl = sorted(desc)
    rows, by_index, by_code = [], collections.defaultdict(set), collections.defaultdict(list)
    for r in csv.DictReader(open(os.path.join(V.OUT, "fault_paths.csv"), encoding="utf-8")):
        if not r["cfg_pointer_word"]:
            continue
        li = (int(r["cfg_pointer_word"], 16) - 0xF1000) // 2
        k = bisect.bisect_right(dl, li) - 1
        if k < 0:
            continue
        di = dl[k]
        a, code, raw = desc[di]
        r3 = int(r["r3"], 16)
        by_index[r3 >> 1].add(code)
        de, en, _ = texts.get(code, ("", "", []))
        row = {"call_site": r["call_site"], "function": r["function"], "r3": f"0x{r3:04X}", "fault_index": r3 >> 1,
               "path": int(r["path"]), "error": int(r["error"]), "cfg_label": li, "descriptor_label": di,
               "descriptor_address": f"0x{a:05X}", "code": f"0x{code:04X}", "text_de": de, "text_en": en}
        rows.append(row)
        by_code[code].append(row)
    ambiguous = {k: v for k, v in by_index.items() if len(v) > 1}
    if ambiguous:
        raise SystemExit(f"ambiguous fault indices: {ambiguous}")
    with open(os.path.join(V.OUT, "fault_codes.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    md = [f"# {V.NAME} ({V.V['role']}) – fault reports and SGBD fault codes", "",
          "Generated by `tools/faultcodes.py`. Each fault report (`fault_report`, R3 = (path << 4) | (error << 1)) is "
          "assigned to the fault-code descriptor label that precedes its debounce label in the label pointer table; "
          f"the descriptor's first word is the code the ECU reports in KWP2000 service 0x18. {len(desc)} descriptors, "
          f"{len(rows)} fault reports, {len(by_index)} fault indices (R3 >> 1), none ambiguous. Texts from "
          f"`{V.V['sgbd']}.prg` (German) and the English SGBD of BMW Standard Tools.", "",
          "| Code | Text (DE) | Text (EN) | Descriptor | Fault indices (R3 >> 1) | Reporting functions | Environment |",
          "|---|---|---|---|---|---|---|"]
    for di in dl:
        a, code, raw = desc[di]
        de, en, uw = texts.get(code, ("", "", []))
        rs = by_code.get(code, [])
        idx = sorted({r["fault_index"] for r in rs})
        fns = sorted({r["function"] for r in rs})
        envt = ", ".join(env.get(u.lower(), u) for u in uw)
        md.append(f"| 0x{code:04X} | {de} | {en} | label {di} @ 0x{a:05X} (`{raw.hex(' ')}`) | "
                  f"{', '.join(f'0x{i:02X}' for i in idx) or '–'} | {', '.join(fns) or '–'} | {envt} |")
    missing = sorted(c for c in texts if c and c not in {v[1] for v in desc.values()})
    md += ["", f"SGBD codes without a descriptor in this image: {', '.join(f'0x{c:04X}' for c in missing) or 'none'}.", ""]
    with open(os.path.join(V.OUT, "fault_codes.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(md))
    print(f"fault_codes: {len(desc)} descriptors, {len(rows)} reports, {len(by_index)} fault indices, "
          f"{len(by_code)} codes reported, missing {len(missing)}")


if __name__ == "__main__":
    main()
