"""DDE6.3 CAN configuration, 0x0B5 (TORQUE_GEARBX) signal reads, fault paths and gearbox calibration.

Reads the image built by build_bins.py and out/calls.json from ppcdis.py; writes out/can.md.

- Message list: 16-byte entries at 0x041B80 (ID u32, 01, bus, object, direction, length, flags).
- Signal descriptors: 6-byte entries at 0x040AF2 (handle u16, record, type, start bit, length).
- Calibration module pointer table: r15 = 0x052C0C (boot code not supplied; the only base for which
  all 427 r15 offsets used in the code yield calibration/constant pointers).
- Fault path -> DTC table: 0x0CC5EA, 4 DTCs (u16) per path.

Usage: python can63.py
"""
import collections
import json
import os

import mem as M

MSG_LIST = (0x041A00, 0x041FE0)
DESC = 0x040AF2
R15 = 0x052C0C
DTC = 0x0CC5EA
READERS = {"4109C0", "42B4A8", "42B5DC", "42B684", "42B718", "42B7E4", "45DDEC", "410948", "42BBEC", "42BAF8"}

# community decoding of 0x0B5 (github.com/HeinrichG-V12/E65_ReverseEngineering, docs/0x0B5.md)
B5_NAMES = {0x70: "CHKSM_TORQ_EGS", 0x71: "ALIV_TORQ_EGS", 0x72: "TORQ_TAR_EGS", 0x73: "TORQ_TAR_ADJR_POS_EGS",
            0x74: "ST_TORQ_TAR_EGS", 0x75: "ST_OTMP_GRB", 0x76: "ST_OBD_GRB", 0x77: "ST_OTMP_ERR_GRB",
            0x78: "ST_LIM_STORQ", 0x79: "TORQ_DRAW_GRB", 0x7A: "TEMP_GRB"}


def messages(m):
    out, p = [], MSG_LIST[0]
    while p < MSG_LIST[1]:
        ident = m.u32(p)
        b = m.bytes(p, 16)
        if ident < 0x800 and b[4] == 1 and b[5] <= 2 and 1 <= b[8] <= 8:
            out.append(dict(at=p, id=ident, bus=b[5], obj=b[6], tx=b[7], length=b[8], flags=b[12:16].hex()))
            p += 16
        else:
            p += 4
    return out


def descriptors(m):
    out, n = [], 0
    while True:
        b = m.bytes(DESC + 6 * n, 6)
        if (b[0] << 8 | b[1]) != n:
            return out
        out.append(dict(handle=n, rec=b[2], type=b[3], start=b[4], length=b[5]))
        n += 1


def curve(m, a):
    n = m.s16(a)
    return [m.s16(a + 2 + 2 * i) for i in range(n)], [m.s16(a + 2 + 2 * n + 2 * i) for i in range(n)]


def main():
    m = M.Mem()
    calls = json.load(open(os.path.join(M.OUT, "calls.json")))
    L = ["# DDE6.3 CAN configuration and gearbox torque interface\n",
         f"Generated by `tools/can63.py` from {M.PRG} + {M.DAT}.\n"]

    L.append("\n## Message list (0x041B80)\n\n| Entry | ID | Bus | Object | Direction | Length | Flags |\n|---|---|---|---|---|---|---|")
    for e in messages(m):
        L.append(f"| {e['at']:06X} | 0x{e['id']:03X} | {e['bus']} | {e['obj']} | {'TX' if e['tx'] else 'RX'} | {e['length']} | {e['flags']} |")

    desc = descriptors(m)
    by = collections.defaultdict(list)
    for d in desc:
        by[d["rec"]].append(d)
    L.append(f"\n## Signal descriptors (0x040AF2, {len(desc)} handles)\n\n| Record | Handles (handle:start+length) |\n|---|---|")
    for r in sorted(by):
        L.append(f"| {r} | " + " ".join(f"{d['handle']:03X}:{d['start']}+{d['length']}" for d in by[r]) + " |")

    reads = collections.defaultdict(list)
    for c in calls:
        r3 = c["args"].get("r3")
        if c["target"] in READERS and r3:
            reads[int(r3, 16)].append(f"{c['at']} (fn_{c['func']})")
    L.append("\n## 0x0B5 TORQUE_GEARBX (record 1) signal reads\n\n| Handle | Bits | Signal | Read at |\n|---|---|---|---|")
    for d in by[1]:
        h = d["handle"]
        L.append(f"| 0x{h:03X} | {d['start']}+{d['length']} | {B5_NAMES.get(h, '(alternative layout)')} | {', '.join(reads.get(h, [])) or '-'} |")

    L.append("\n## Fault paths of the gearbox interface (DTC table 0x0CC5EA)\n\n| Path | DTCs |\n|---|---|")
    for p in (0xBE, 0xBF, 0xC3, 0x1EA):
        L.append(f"| 0x{p:03X} | " + " ".join(f"{m.u16(DTC + 8 * p + 2 * k):04X}" for k in range(4)) + " |")

    L.append("\n## Gearbox calibration\n")
    rx, prep, lim = (m.u32(R15 + o) for o in (0x2C0, 0x2E0, 0x2E4))
    L.append(f"- 0x0B5 receive block `*(r15+0x2C0)` = 0x{rx:06X}: positive-intervention path flag `+0x389` = {m.u8(rx + 0x389)}, "
             f"default `TORQ_TAR_ADJR_POS_EGS` `+0x3FA` = {m.s16(rx + 0x3FA)} (0.1 Nm), torque scaling `+0x34` = "
             f"offset {m.s16(rx + 0x34)}, factor {m.s16(rx + 0x36)}/1000")
    L.append(f"- Increase/reduction preparation `*(r15+0x2E0)` = 0x{prep:06X}: increase cap `+0x50` = {m.s16(prep + 0x50)}, "
             f"ramps `+0x48`/`+0x54` = {m.bytes(prep + 0x48, 4).hex()}/{m.bytes(prep + 0x54, 4).hex()}")
    xs, ys = curve(m, prep + 4)
    L.append(f"- Reduction ceiling curve `+0x04` over 0x7F98C4: x = {xs}, y = {ys}")
    L.append(f"- Per-gear torque limit `*(r15+0x2E4)` = 0x{lim:06X} (curves over 0x7F98C4, 0.1 Nm):\n")
    L.append("| Gear | Curve | x | y |\n|---|---|---|---|")
    for g, o in (("R", 0x2D6), ("N / other", 0x30), ("1", 0x162), ("2", 0x1A0), ("3", 0x1DE), ("4", 0x21C), ("5", 0x25A), ("6", 0x298)):
        xs, ys = curve(m, lim + o)
        L.append(f"| {g} | 0x{lim + o:06X} | {xs[0]}..{xs[-1]} ({len(xs)}) | {sorted(set(ys))} |")

    open(os.path.join(M.OUT, "can.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote out/can.md")


if __name__ == "__main__":
    main()
