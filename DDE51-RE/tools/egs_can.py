"""Cross-check the DDE5.1 CAN configuration against the E65 6HP26 transmission (EGS) software.

Transmission software for the M67D40 (= M67D39 3.9 l in BMW SP-Daten naming) in BMW-SPdaten-v.60.1/E65/data:
  GKE192  GS19.02  programs 7534928A (assembly 7537217, data A7537218) and 7534929A (7537233, A7537234)
  GKE194  GS19.04  program 7557063A (assembly 7559200, data A7559201)

The transmission program code is encrypted in the exchange files (entropy ~7.95 bit/byte); the CAN
configuration tables are plain. They use the same framework as the DDE5.1 (TouCAN bases 0x307080 /
0x307480): a header with (pointer, count) pairs, then 24-byte message entries
  [0] index  [1] 1 = transmit  [4] cycle/timeout code  [12..15] identifier  [20] length

DDE5.1 message objects: 12-byte entries from 0x9524 in 7809330A ([2] object, [4] length, [8..11] identifier).

Usage: python egs_can.py   -> out/egs_can.md
"""
import os
import struct
import subprocess
import sys

import mem as M

HEX2BIN = os.path.join(M.REPO, "DDE41A-RE", "tools", "hex2bin.py")
EGS_BIN = os.path.join(M.ROOT, "egs", "bin")
SOFTWARE = [
    # name, folder, program file, image base, list headers (pointer, count), PT-CAN list index
    ("GS19.02 7534929A", "GKE192", "7534929A.0PA", 0x10000, [(0x15134, 0x16), (0x15344, 0x14)]),
    ("GS19.04 7557063A", "GKE194", "7557063A.0pa", 0x00000, [(0xB4AA4, 0x1A), (0xB4D14, 0x0F)]),
]
GEARBOX_IDS = {0x0B5: "TORQUE_GEARBX", 0x0BA: "GEARBX_DATA", 0x1A2: "GEARBX_DATA2"}


def image(folder, fn, base):
    os.makedirs(EGS_BIN, exist_ok=True)
    out = os.path.join(EGS_BIN, os.path.splitext(fn)[0] + ".bin")
    if not os.path.exists(out):
        subprocess.run([sys.executable, HEX2BIN, os.path.join(M.SP, "data", folder, fn), out, "--base", hex(base)],
                       check=True, capture_output=True)
    return open(out, "rb").read()


def egs_lists(d, base, headers):
    lists = []
    for ptr, cnt in headers:
        ents = []
        for k in range(cnt):
            e = d[ptr - base + 24 * k: ptr - base + 24 * (k + 1)]
            ents.append(dict(tx=bool(e[1]), cyc=e[4], id=struct.unpack(">I", e[12:16])[0], length=e[20]))
        lists.append(ents)
    return lists


def dde_list(m):
    ents, a = [], 0x9524
    while True:
        e = m.bytes(a, 12)
        ident = struct.unpack(">I", e[8:12])[0]
        if e[0] == 0xFF or ident > 0x7FF:
            break
        if ident:
            ents.append(dict(entry=(a - 0x9524) // 12, obj=e[2], length=e[4], id=ident))
        a += 12
    return ents


def main():
    m = M.Mem()
    dde = dde_list(m)
    dde_ids = {}
    for e in dde:
        dde_ids.setdefault(e["id"], []).append(e)
    egs = {}
    for name, folder, fn, base, hdr in SOFTWARE:
        egs[name] = egs_lists(image(folder, fn, base), base, hdr)

    lines = ["# DDE5.1 vs. transmission (GS19) CAN configuration\n",
             "Generated by `tools/egs_can.py`. EGS lengths are the configured message lengths; DDE lengths are the "
             "configured lengths of its message objects (entries from 0x9524).\n"]
    for name, lists in egs.items():
        lines.append(f"\n## {name}\n")
        for li, ents in enumerate(lists):
            lines.append(f"\nList {li + 1} ({len(ents)} messages):\n\n| ID | Direction (EGS) | Length (EGS) | Cycle code | In DDE list | Length (DDE) |\n|---|---|---|---|---|---|")
            for e in ents:
                d = dde_ids.get(e["id"], [])
                tag = GEARBOX_IDS.get(e["id"], "")
                lines.append(f"| 0x{e['id']:03X} {tag} | {'TX' if e['tx'] else 'RX'} | {e['length']} | {e['cyc']} | "
                             f"{'yes' if d else ''} | {', '.join(str(x['length']) for x in d)} |")
    all_egs = {e["id"] for lists in egs.values() for e in lists[0]}
    lines.append("\n## DDE messages not in any EGS PT-CAN list\n")
    lines.append(", ".join(f"0x{i:03X}" for i in sorted(set(dde_ids) - all_egs)) + "\n")
    open(os.path.join(M.OUT, "egs_can.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    for name, lists in egs.items():
        print(name, "PT-CAN:", " ".join(f"{'TX:' if e['tx'] else ''}{e['id']:03X}/{e['length']}" for e in lists[0]))
    print("DDE:", " ".join(f"{e['id']:03X}/{e['length']}" for e in dde))


if __name__ == "__main__":
    main()

