"""PowerPC (MPC5xx) disassembler and cross-reference builder for DDE5.1 / EDC16C1.

- Linear disassembly of the code regions (fixed 4-byte instructions) with capstone for the text.
- Function starts: bl targets, `mflr r0` / `stwu r1,-n(r1)` prologues, and code after an unconditional
  end (blr/bctr/b) that is itself a branch target or prologue.
- Register constant tracking inside straight-line code (lis/addi/addis/ori/oris/mr), reset at branch
  targets and after calls, resolves absolute addresses of loads, stores and address constants.
- r13 (small-data base, RAM) and r2 (small-data 2 base) are set in the boot code that isn't supplied;
  their values come from out/bases.json once determined (see find_bases.py). Until then accesses are
  recorded symbolically as r13+off / r2+off.

Outputs (out/): listing.asm, functions.csv, xrefs.json, calls.json
Usage: python ppcdis.py
"""
import bisect
import collections
import csv
import json
import os
import struct

import capstone

import mem as M

LOADS = {32: 4, 33: 4, 34: 1, 35: 1, 40: 2, 41: 2, 42: 2, 43: 2}          # opcode -> size
STORES = {36: 4, 37: 4, 38: 1, 39: 1, 44: 2, 45: 2}
FLOADS = {48: 4, 49: 4, 50: 8, 51: 8}
FSTORES = {52: 4, 53: 4, 54: 8, 55: 8}
UPDATE = {33, 35, 41, 43, 37, 39, 45, 49, 51, 53, 55}
X_RA_DEST = {28, 60, 124, 284, 316, 412, 444, 476, 24, 536, 792, 824, 26, 922, 954}
X_STORE = {151, 183, 215, 247, 407, 439, 663, 695, 727, 759, 918, 662, 150}
X_NODEST = {0, 32, 86, 54, 278, 470, 1014, 854, 598, 144, 146, 210, 242, 306, 370, 566, 4}
X_INDEXED = {23: ('rx', 4), 55: ('rx', 4), 87: ('rx', 1), 119: ('rx', 1), 279: ('rx', 2), 311: ('rx', 2),
             343: ('rx', 2), 375: ('rx', 2), 151: ('wx', 4), 183: ('wx', 4), 215: ('wx', 1), 247: ('wx', 1),
             407: ('wx', 2), 439: ('wx', 2)}
CALL_CLOBBER = [0] + list(range(3, 13))


def s16(x):
    return x - 0x10000 if x & 0x8000 else x


def load_json(name, default):
    p = os.path.join(M.OUT, name)
    return json.load(open(p)) if os.path.exists(p) else default


class Null:
    def write(self, _):
        pass


def branch_target(w, a):
    op = w >> 26
    if op == 18:
        li = w & 0x03FFFFFC
        if li & 0x02000000:
            li -= 0x04000000
        return (li if w & 2 else a + li) & 0xFFFFFFFF, bool(w & 1), True
    if op == 16:
        bd = w & 0xFFFC
        if bd & 0x8000:
            bd -= 0x10000
        return (bd if w & 2 else a + bd) & 0xFFFFFFFF, bool(w & 1), (w >> 21) & 0x14 == 0x14
    return None, False, False


def is_end(w):
    op = w >> 26
    if w in (0x4E800020, 0x4E800420):          # blr, bctr
        return True
    return op == 18 and not (w & 1)            # b (tail call / jump)


def main():
    mem = M.Mem()
    bases = load_json("bases.json", {})
    r13 = int(bases["r13"], 16) if "r13" in bases else None
    r2 = int(bases["r2"], 16) if "r2" in bases else None
    r14 = int(bases["r14"], 16) if "r14" in bases else None
    names = {int(k, 16): v for k, v in load_json("names.json", {}).items()}

    words = {}
    for lo, hi in M.CODE:
        for a in range(lo, hi, 4):
            words[a] = mem.u32(a)

    # pass 1: branch targets and function starts
    targets, calls = set(), collections.defaultdict(set)
    for a, w in words.items():
        t, lk, _ = branch_target(w, a)
        if t is None:
            continue
        if lk:
            calls[t].add(a)
        else:
            targets.add(t)
    starts = {t for t in calls if t in words}
    for a, w in words.items():
        if w == 0x7C0802A6 and (words.get(a + 4, 0) >> 16 == 0x9421 or words.get(a + 8, 0) >> 16 == 0x9421):
            starts.add(a)
        elif w >> 16 == 0x9421 and words.get(a - 4) != 0x7C0802A6:
            prev = words.get(a - 4)
            if prev is None or is_end(prev) or prev == 0xFFFFFFFF or prev == 0:
                starts.add(a)
    for a, w in words.items():
        if is_end(w) and a + 4 in words and a + 4 in targets and words[a + 4] not in (0, 0xFFFFFFFF):
            pass  # local labels after a return are usually still part of the same function
    starts = sorted(s for s in starts if words.get(s) not in (None, 0xFFFFFFFF))

    # pass 2: per-function constant tracking
    md = capstone.Cs(capstone.CS_ARCH_PPC, capstone.CS_MODE_32 | capstone.CS_MODE_BIG_ENDIAN)
    xrefs = collections.defaultdict(list)       # key: "XXXXXX" absolute or "r13+off" -> [insn, func, kind, size]
    callsites, funcs = [], []
    listing = open(os.path.join(M.OUT, "listing.asm"), "w", encoding="utf-8")
    listing.write("; DDE5.1 (EDC16C1) 7809330A + V7810913 - generated by tools/ppcdis.py\n")
    listing.write(f"; r13 = {bases.get('r13', 'unknown')}  r2 = {bases.get('r2', 'unknown')}\n")

    BASE_REGS = (2, 13, 14) if r14 is not None else (2, 13)

    def ea_key(base_reg, val, off):
        if val is not None:
            return (val + off) & 0xFFFFFFFF
        if base_reg == 13:
            return (r13 + off) if r13 is not None else f"r13{off:+#x}"
        if base_reg == 2:
            return (r2 + off) if r2 is not None else f"r2{off:+#x}"
        if base_reg == 14 and r14 is not None:
            return r14 + off
        return None

    def keystr(k):
        return f"{k:06X}" if isinstance(k, int) else k

    def ann(k):
        if isinstance(k, int):
            n = names.get(k)
            tag = "RAM" if M.is_ram(k) else "CAL" if M.is_cal(k) else "CODE" if M.is_code(k) else "ROM" if M.is_rom(k) else "ABS"
            return f"{tag} {k:06X}" + (f" {n}" if n else "")
        return k

    bounds = starts + [10 ** 9]
    for fi, f in enumerate(starts):
        end = f
        # function extends until the next function start (or end of region)
        nxt = bounds[fi + 1]
        reg = {}
        local = set()
        a = f
        insns = []
        while a < nxt and a in words:
            insns.append(a)
            a += 4
        end = a
        for a in insns:
            t, lk, _ = branch_target(words[a], a)
            if t is not None and not lk and f <= t < end:
                local.add(t)
        writes, first_w = collections.Counter(), {}
        for emit in (False, True):
            reg = {}
            out = listing if emit else Null()
            xr = xrefs if emit else collections.defaultdict(list)
            cs = callsites if emit else []
            keep = {r for r, n in writes.items() if n == 1}
            n_calls, callees = 0, set()
            out.write(f"\n;{'=' * 78}\n; fn_{f:06X}  ({len(insns)} insns, callers {len(calls.get(f, ()))})\n;{'=' * 78}\n")
            out.write(f"fn_{f:06X}:\n")
            for a in insns:
                w = words[a]
                if a in local and a != f:
                    reg = {r: v for r, v in reg.items() if r in keep and first_w[r] < a}
                    out.write(f"loc_{a:06X}:\n")
                txt = ""
                if emit:
                    for ins in md.disasm(struct.pack(">I", w), a):
                        txt = f"{ins.mnemonic:<9}{ins.op_str}"
                    if not txt:
                        txt = f".long    0x{w:08X}"
                note = ""
                op, rt, ra, imm = w >> 26, (w >> 21) & 31, (w >> 16) & 31, w & 0xFFFF
                dest = []
                if op == 15:                                        # lis / addis
                    v = (imm << 16) if ra == 0 else (reg[ra] + (s16(imm) << 16)) & 0xFFFFFFFF if ra in reg else None
                    dest = [(rt, v)]
                elif op == 14:                                      # li / addi
                    if ra == 0:
                        v = s16(imm) & 0xFFFFFFFF
                    else:
                        k = ea_key(ra, reg.get(ra), s16(imm))
                        v = k if isinstance(k, int) else None
                        if k is not None and (ra in BASE_REGS or ra in reg):
                            if not isinstance(k, int) or M.is_ram(k) or M.is_cal(k) or M.is_rom(k):
                                xr[keystr(k)].append([a, f, "a", 0])
                                note = ann(k)
                    dest = [(rt, v)]
                elif op in (24, 25):                                # ori / oris
                    v = reg.get(rt)
                    if v is not None:
                        v = v | (imm << (16 if op == 25 else 0))
                    if rt == ra == 0 and imm == 0:
                        dest = []
                    else:
                        dest = [(ra, v)]
                        if v is not None and op == 24 and (M.is_ram(v) or M.is_cal(v) or M.is_rom(v)):
                            xr[keystr(v)].append([a, f, "a", 0])
                            note = ann(v)
                elif op in LOADS or op in STORES or op in FLOADS or op in FSTORES:
                    k = ea_key(ra, reg.get(ra), s16(imm)) if ra != 0 else s16(imm) & 0xFFFFFFFF
                    if k is not None and (ra in BASE_REGS or ra in reg):
                        kind = "r" if (op in LOADS or op in FLOADS) else "w"
                        size = {**LOADS, **STORES, **FLOADS, **FSTORES}[op]
                        xr[keystr(k)].append([a, f, kind, size])
                        note = ann(k)
                    if op in LOADS:
                        dest.append((rt, None))
                    if op in UPDATE:
                        dest.append((ra, None))
                elif op == 46:                                      # lmw
                    dest = [(r, None) for r in range(rt, 32)]
                elif op in (20, 21, 23, 28, 29, 26, 27):            # rotate/logical immediate -> rA
                    dest = [(ra, None)]
                elif op == 31:
                    xo = (w >> 1) & 0x3FF
                    rb = (w >> 11) & 31
                    if xo in X_INDEXED:
                        base_v = reg.get(ra) if ra in reg else reg.get(rb) if rb in reg else None
                        if base_v is not None and (M.is_ram(base_v) or M.is_cal(base_v) or M.is_rom(base_v)):
                            kind, size = X_INDEXED[xo]
                            xr[keystr(base_v)].append([a, f, kind, size])
                            note = ann(base_v) + " [indexed]"
                    if xo == 444 and rt == rb:                      # mr
                        dest = [(ra, reg.get(rt))]
                    elif xo in X_RA_DEST:
                        dest = [(ra, None)]
                    elif xo in X_STORE or xo in X_NODEST:
                        dest = []
                    else:
                        dest = [(rt, None)]
                elif op in (7, 8, 12, 13, 34, 35):
                    dest = [(rt, None)]
                elif op in (16, 18):
                    t, lk, _ = branch_target(w, a)
                    if lk:
                        n_calls += 1
                        callees.add(t)
                        args = {f"r{r}": (f"0x{reg[r]:X}" if reg.get(r) is not None else None) for r in range(3, 11) if r in reg}
                        cs.append({"at": f"{a:06X}", "func": f"{f:06X}", "target": f"{t:06X}", "args": args})
                        note = f"-> fn_{t:06X}" if t in calls else f"-> {t:06X}"
                        for r in CALL_CLOBBER:
                            reg.pop(r, None)
                    elif t is not None:
                        note = f"-> loc_{t:06X}" if f <= t < end else f"-> {t:06X}"
                for r, v in dest:
                    if not emit:
                        writes[r] += 1
                        first_w.setdefault(r, a)
                    if v is None:
                        reg.pop(r, None)
                    else:
                        reg[r] = v & 0xFFFFFFFF
                line = f"  {a:06X}: {w:08X}  {txt}"
                if note:
                    line = f"{line:<60} ; {note}"
                out.write(line + "\n")
                if is_end(w):
                    reg = {r: v for r, v in reg.items() if r in keep}
        funcs.append(dict(start=f"{f:06X}", end=f"{end:06X}", insns=len(insns), callers=len(calls.get(f, ())),
                          calls=n_calls, callees=" ".join(f"{c:06X}" for c in sorted(callees))))
    listing.close()

    with open(os.path.join(M.OUT, "functions.csv"), "w", newline="") as fh:
        wr = csv.DictWriter(fh, fieldnames=list(funcs[0].keys()))
        wr.writeheader()
        wr.writerows(funcs)
    json.dump({k: v for k, v in sorted(xrefs.items())}, open(os.path.join(M.OUT, "xrefs.json"), "w"))
    json.dump(callsites, open(os.path.join(M.OUT, "calls.json"), "w"))
    ext_calls = collections.Counter(c["target"] for c in callsites if not M.is_code(int(c["target"], 16)))
    print(f"{len(starts)} functions, {sum(f['insns'] for f in funcs)} instructions, {len(xrefs)} referenced addresses, "
          f"{len(callsites)} calls ({sum(ext_calls.values())} into unsupplied code, {len(ext_calls)} targets)")


if __name__ == "__main__":
    main()
